import re

def parse_area(x):
    if pd.isna(x):
        return None

    x = str(x).lower().strip()

    number = re.findall(r"\d+\.?\d*", x)

    if len(number) == 0:
        return None

    area = float(number[0])

    if "sqm" in x:
        area = area * 10.764

    return area

