import re

def parse_floor(x):
    if pd.isna(x):
        return None

    x = str(x).lower().strip()

    if "ground" in x:
        return 0

    numbers = re.findall(r"\d+", x)

    if len(numbers) == 0:
        return None

    return int(numbers[0])

